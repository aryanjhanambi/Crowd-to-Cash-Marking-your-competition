"""Dependency-free linear-quadratic mean-field game benchmark.

The state q is a trader's inventory and u is their trading rate:

    dq_t = u_t dt + sigma dW_t.

The running cost is

    eta*u^2/2 + gamma*q^2/2 + kappa*(q - mean_q)^2/2,

with terminal cost terminal_penalty*q_T^2/2.  A quadratic value function reduces
the HJB--Fokker--Planck system to a forward-backward system for the value-function
coefficients and the first two moments of the population density.
"""

from __future__ import annotations

import argparse
import csv
import math
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class ModelParameters:
    """Parameters of the baseline market game."""

    horizon: float = 1.0
    steps: int = 1_000
    trading_cost: float = 1.0
    inventory_penalty: float = 0.25
    crowding_strength: float = 0.75
    terminal_penalty: float = 2.0
    noise: float = 0.20
    initial_mean: float = 1.0
    initial_variance: float = 0.16
    relaxation: float = 0.35
    tolerance: float = 1e-10
    max_iterations: int = 10_000

    def validate(self) -> None:
        if self.horizon <= 0:
            raise ValueError("horizon must be positive")
        if self.steps < 2:
            raise ValueError("steps must be at least 2")
        if self.trading_cost <= 0:
            raise ValueError("trading_cost must be positive")
        if min(
            self.inventory_penalty,
            self.crowding_strength,
            self.terminal_penalty,
            self.noise,
            self.initial_variance,
        ) < 0:
            raise ValueError("penalties, noise, and variance must be non-negative")
        if not 0 < self.relaxation <= 1:
            raise ValueError("relaxation must be in (0, 1]")


@dataclass(frozen=True)
class Solution:
    """Time paths defining the Gaussian mean-field equilibrium."""

    time: tuple[float, ...]
    quadratic_value: tuple[float, ...]
    linear_value: tuple[float, ...]
    mean_inventory: tuple[float, ...]
    inventory_variance: tuple[float, ...]
    iterations: int
    residual: float

    def control(self, index: int, inventory: float, trading_cost: float) -> float:
        """Return the equilibrium trading rate at one time-grid index."""

        return -(
            self.quadratic_value[index] * inventory + self.linear_value[index]
        ) / trading_cost


def _backward_coefficients(
    params: ModelParameters, mean_guess: list[float], dt: float
) -> tuple[list[float], list[float]]:
    """Backward Euler solve for value V(t,q)=a(t)q^2/2+b(t)q+c(t)."""

    n = params.steps
    eta = params.trading_cost
    a = [0.0] * (n + 1)
    b = [0.0] * (n + 1)
    a[n] = params.terminal_penalty
    b[n] = 0.0

    # The ODEs run backward from the terminal cost.  The semi-implicit updates
    # avoid the most common explicit-Euler instability in the linear b equation.
    for i in range(n - 1, -1, -1):
        a_next = a[i + 1]
        a[i] = a_next - dt * (
            a_next * a_next / eta
            - params.inventory_penalty
            - params.crowding_strength
        )
        denominator = 1.0 + dt * a[i] / eta
        b[i] = (b[i + 1] - dt * params.crowding_strength * mean_guess[i]) / denominator
    return a, b


def _forward_moments(
    params: ModelParameters, a: list[float], b: list[float], dt: float
) -> tuple[list[float], list[float]]:
    """Propagate population mean and variance under the optimal feedback."""

    n = params.steps
    eta = params.trading_cost
    mean = [0.0] * (n + 1)
    variance = [0.0] * (n + 1)
    mean[0] = params.initial_mean
    variance[0] = params.initial_variance

    for i in range(n):
        mean[i + 1] = mean[i] + dt * (-(a[i] * mean[i] + b[i]) / eta)
        variance[i + 1] = variance[i] + dt * (
            -2.0 * a[i] * variance[i] / eta + params.noise**2
        )
        # Tiny negative values can arise solely from floating-point roundoff.
        if -1e-14 < variance[i + 1] < 0:
            variance[i + 1] = 0.0
        if variance[i + 1] < 0:
            raise ArithmeticError(
                "variance became negative; increase steps or inspect parameters"
            )
    return mean, variance


def solve_moments(params: ModelParameters | None = None) -> Solution:
    """Solve the MFG consistency condition by relaxed fixed-point iteration."""

    params = params or ModelParameters()
    params.validate()
    dt = params.horizon / params.steps
    time = tuple(i * dt for i in range(params.steps + 1))

    # A linear decay is only an initial belief about the crowd. At equilibrium,
    # the belief must equal the population path generated by optimal controls.
    mean_guess = [params.initial_mean * (1.0 - 0.5 * t / params.horizon) for t in time]
    residual = math.inf

    for iteration in range(1, params.max_iterations + 1):
        a, b = _backward_coefficients(params, mean_guess, dt)
        generated_mean, variance = _forward_moments(params, a, b, dt)
        residual = max(
            abs(generated_mean[i] - mean_guess[i])
            for i in range(params.steps + 1)
        )
        mean_guess = [
            (1.0 - params.relaxation) * mean_guess[i]
            + params.relaxation * generated_mean[i]
            for i in range(params.steps + 1)
        ]
        if residual < params.tolerance:
            # Recompute once with the converged mean so all returned paths satisfy
            # the same discretized equations.
            a, b = _backward_coefficients(params, mean_guess, dt)
            mean, variance = _forward_moments(params, a, b, dt)
            return Solution(
                time=time,
                quadratic_value=tuple(a),
                linear_value=tuple(b),
                mean_inventory=tuple(mean),
                inventory_variance=tuple(variance),
                iterations=iteration,
                residual=residual,
            )

    raise RuntimeError(
        f"mean-field iteration did not converge after {params.max_iterations} "
        f"iterations (residual={residual:.3e})"
    )


def gaussian_density(inventory: float, mean: float, variance: float) -> float:
    """Evaluate the Gaussian population density implied by the moment solution."""

    if variance <= 0:
        raise ValueError("variance must be positive to evaluate a density")
    return math.exp(-0.5 * (inventory - mean) ** 2 / variance) / math.sqrt(
        2.0 * math.pi * variance
    )


def write_csv(solution: Solution, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            ["time", "a", "b", "mean_inventory", "inventory_variance"]
        )
        writer.writerows(
            zip(
                solution.time,
                solution.quadratic_value,
                solution.linear_value,
                solution.mean_inventory,
                solution.inventory_variance,
                strict=True,
            )
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=Path("results/baseline.csv")
    )
    args = parser.parse_args()
    solution = solve_moments()
    write_csv(solution, args.output)
    print(f"converged in {solution.iterations} iterations")
    print(f"fixed-point residual: {solution.residual:.3e}")
    print(f"initial mean inventory: {solution.mean_inventory[0]:.6f}")
    print(f"terminal mean inventory: {solution.mean_inventory[-1]:.6f}")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()

